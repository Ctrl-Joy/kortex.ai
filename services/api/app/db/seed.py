def seed_core(db: Session) -> dict[str, int]:
    created = {"store": 0, "staff": 0, "products": 0, "zones": 0}
    settings = get_settings()

    if db.get(Store, STORE_ID) is None:
        db.add(Store(id=STORE_ID, name="KORTEX Demo Store", city="Bengaluru · Koramangala", timezone="Asia/Kolkata"))
        created["store"] += 1

    for username, display, role in (
        ("manager", "Priya Raman (Store Manager)", StaffRole.MANAGER),
        ("attendant", "Arjun Mehta (Floor Attendant)", StaffRole.ATTENDANT),
    ):
        if db.scalar(select(StaffUser).where(StaffUser.username == username)) is None:
            db.add(
                StaffUser(
                    username=username,
                    display_name=display,
                    role=role,
                    password_hash=hash_password(settings.seed_staff_password),
                )
            )
            created["staff"] += 1

    for spec in DEMO_PRODUCTS:
        if db.scalar(select(Product).where(Product.sku == spec["sku"])) is None:
            data = {k: v for k, v in spec.items() if k != "body"}
            db.add(Product(barcode=barcode.with_check_digit(spec["body"]), **data))
            created["products"] += 1

    if db.get(ZoneBinding, DEMO_ZONE) is None:
        db.add(ZoneBinding(zone_id=DEMO_ZONE, label="Shelf A1 · Demo interaction zone"))
        created["zones"] += 1

    db.commit()
    return created


# --------------------------------------------------------------------------
# Historical demo sessions (for dashboard charts). Generated by running the
# real pipeline, then shifting the session's timestamps into the past.
# --------------------------------------------------------------------------


def _shift_session(db: Session, session_id: str, delta: timedelta) -> None:
    """Move every timestamp belonging to one seeded session into the past."""
    db.flush()
    targets = [
        (ShoppingSession, ShoppingSession.id, ("started_at", "last_activity_at", "ended_at")),
        (ScanEvent, ScanEvent.session_id, ("occurred_at", "received_at", "voided_at")),
        (VisionEvent, VisionEvent.session_id, ("occurred_at", "received_at", "decided_at", "finalize_after")),
        (SensorEvent, SensorEvent.session_id, ("occurred_at", "received_at")),
        (ReconciliationResult, ReconciliationResult.session_id, ("created_at",)),
        (Discrepancy, Discrepancy.session_id, ("created_at", "updated_at", "resolved_at")),
        (ResolutionAction, ResolutionAction.session_id, ("created_at",)),
        (AuditEvent, AuditEvent.session_id, ("occurred_at",)),
        (CheckoutRecord, CheckoutRecord.session_id, ("authorized_at", "exited_at")),
    ]
    for model, key, cols in targets:
        for row in db.scalars(select(model).where(key == session_id)):
            for col in cols:
                value = getattr(row, col)
                if value is not None:
                    setattr(row, col, value - delta)
            if hasattr(row, "updated_at") and model is Discrepancy:
                row.updated_at = row.created_at if row.resolved_at is None else row.resolved_at


def seed_history(db: Session, sessions_count: int = 18) -> int:
    """Create labelled historical demo sessions once (idempotent via a flag)."""
    from app.services import checkout, pipeline, resolutions, sessions
    from app.services.audit import Actor
    from app.services.pipeline import VisionInput

    if db.get(SystemSetting, HISTORY_FLAG) is not None:
        return 0

    rng = random.Random(20261010)
    sim = Actor(ActorType.SIMULATOR, "seed-history")
    products = list(db.scalars(select(Product).order_by(Product.sku)))
    by_sku = {p.sku: p for p in products}
    now = utcnow()
    made = 0

    for i in range(sessions_count):
        days_ago = rng.randint(0, 6)
        delta = timedelta(days=days_ago, hours=rng.randint(1, 9), minutes=rng.randint(0, 59))
        if days_ago == 0:
            delta = timedelta(hours=rng.randint(2, 6), minutes=rng.randint(0, 59))
        session, _ = sessions.create_session(
            db, actor=sim, is_demo=True, monitor_zone=None, label=f"Seed shopper {i + 1:02d}"
        )
        session.zone_id = DEMO_ZONE
        picks = rng.sample(products, k=rng.randint(1, 3))
        t = now - timedelta(minutes=10)
        for p in picks:
            t += timedelta(seconds=rng.randint(20, 60))
            pipeline.process_scan(
                db,
                session,
                code=p.barcode,
                method="CAMERA_BARCODE",
                actor=sim,
                source=EventSource.SIMULATED,
                is_simulated=True,
                occurred_at=t,
            )
            if rng.random() < 0.7:
                pipeline.ingest_vision_event(
                    db,
                    VisionInput(
                        external_event_id=new_id("SEEDVE", 12),
                        zone_id=DEMO_ZONE,
                        session_id=session.id,
                        event_type=VisionEventType.PICKUP,
                        occurred_at=t - timedelta(seconds=3),
                        source=EventSource.SIMULATED,
                        is_simulated=True,
                        product_id=p.id,
                        model_confidence=round(rng.uniform(0.78, 0.95), 2),
                        track_frames=rng.randint(6, 20),
                        track_id=f"seed-{i}-{p.sku}",
                    ),
                    actor=sim,
                )
        roll = rng.random()
        if roll < 0.45:
            other = by_sku[rng.choice([s for s in by_sku if s not in {p.sku for p in picks}])]
            pipeline.ingest_vision_event(
                db,
                VisionInput(
                    external_event_id=new_id("SEEDVE", 12),
                    zone_id=DEMO_ZONE,
                    session_id=session.id,
                    event_type=VisionEventType.PICKUP,
                    occurred_at=t + timedelta(seconds=5),
                    source=EventSource.SIMULATED,
                    is_simulated=True,
                    product_id=other.id,
                    model_confidence=round(rng.uniform(0.35, 0.92), 2),
                    track_frames=rng.randint(3, 14),
                    track_id=f"seed-{i}-extra",
                ),
                actor=sim,
            )
            pipeline.finalize_pending(db, session_id=session.id, force=True)
            from app.services import discrepancies

            for d in discrepancies.open_for_session(db, session.id):
                outcome = rng.random()
                staff = Actor(ActorType.STAFF, "seed-attendant")
                if outcome < 0.4 and "ADD_TO_CART" in d.customer_options and d.state == "AWAITING_CUSTOMER":
                    resolutions.customer_action(db, session, d, "ADD_TO_CART", actor=sim)
                elif outcome < 0.7:
                    resolutions.staff_action(
                        db,
                        session,
                        d,
                        action="DISMISS",
                        reason="Seeded history: reviewed, item left on shelf.",
                        actor=staff,
                    )
                elif outcome < 0.85:
                    resolutions.staff_action(
                        db,
                        session,
                        d,
                        action="RESOLVE",
                        reason="Seeded history: verified basket at exit.",
                        actor=staff,
                    )
                # else: leave open → shows up as awaiting review
        pipeline.finalize_pending(db, session_id=session.id, force=True)
        if days_ago > 0 or rng.random() < 0.6:
            try:
                checkout.authorize(db, session, actor=sim)
                checkout.confirm_exit(db, session, actor=sim)
            except checkout.CheckoutDenied:
                pass  # authorize() commits the denial record; session stays blocked
        db.flush()
        _shift_session(db, session.id, delta)
        db.commit()
        made += 1

    db.add(SystemSetting(key=HISTORY_FLAG, value={"sessions": made, "seeded_at": now.isoformat()}, updated_by="seed"))
    db.commit()
    return made


def run(with_history: bool = True) -> dict[str, int]:
    from app.db.init_db import init_db
    from app.db.session import SessionLocal

    init_db()
    with SessionLocal() as db:
        result = seed_core(db)
        if with_history:
            result["history_sessions"] = seed_history(db)
    return result


if __name__ == "__main__":  # pragma: no cover
    import sys

    logging.basicConfig(level=logging.INFO)
    print(run(with_history="--no-history" not in sys.argv))
